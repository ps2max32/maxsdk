#!/usr/bin/env python3
"""Generate the hardware headers, syscall stubs and host field tests.

    python3 -I gen/gen.py            (from the repo root)

The outputs are committed, so users of the SDK do not need Python.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import hw_desc as D  # noqa: E402

HEADER = "/* Generated by gen/gen.py from gen/hw_desc.py. Do not edit. */\n"


def check_fields(what, width, fields):
    used = 0
    names = set()
    for name, lsb, w in fields:
        assert name not in names, f"{what}: duplicate field {name}"
        names.add(name)
        assert w > 0 and lsb + w <= width, f"{what}.{name} does not fit in {width} bits"
        bits = ((1 << w) - 1) << lsb
        assert not used & bits, f"{what}.{name} overlaps another field"
        used |= bits


def field_defines(prefix, fields):
    out = []
    for name, lsb, w in fields:
        out.append(f"#define MX_{prefix}_{name}_SHIFT {lsb}")
        out.append(f"#define MX_{prefix}_{name}_MASK 0x{(1 << w) - 1:X}ull")
    return out


def gen_regs():
    out = [HEADER, "#ifndef MX_HW_REGS_H", "#define MX_HW_REGS_H", ""]
    out.append("/* Single registers: address and fields. */")
    for name, addr, width, fields in D.REGS:
        check_fields(name, width, fields)
        out.append(f"#define MX_{name} 0x{addr:08X}u /* {width} bit */")
        out += field_defines(name, fields)
        out.append("")
    out.append("/* Register blocks: MX_<BLOCK>_<UNIT> is the base, MX_<BLOCK>_<UNIT>_<REG> the address,")
    out.append("   MX_<BLOCK>_<REG>_<FIELD>_* the fields. */")
    for block, units, regs in D.BLOCKS:
        for unit, base in units.items():
            out.append(f"#define MX_{block}_{unit} 0x{base:08X}u")
            for reg, off, _ in regs:
                out.append(f"#define MX_{block}_{unit}_{reg} 0x{base + off:08X}u")
        for reg, off, fields in regs:
            check_fields(f"{block}_{reg}", 32, fields)
            out.append(f"#define MX_{block}_{reg}_OFFSET 0x{off:02X}u")
            out += field_defines(f"{block}_{reg}", fields)
        out.append("")
    out.append("/* Fixed addresses. */")
    for name, addr in D.ADDRS:
        out.append(f"#define MX_{name} 0x{addr:08X}u")
    out += ["", "#endif", ""]
    return "\n".join(out)


def gen_formats():
    out = [HEADER, "#ifndef MX_HW_FORMATS_H", "#define MX_HW_FORMATS_H", ""]
    for name, width, fields in D.FORMATS:
        check_fields(name, width, fields)
        out.append(f"/* {name} ({width} bit) */")
        out += field_defines(name, fields)
        out.append("")
    out.append("/* Enumerations. */")
    for name, items in D.ENUMS:
        for item, value in items.items():
            out.append(f"#define MX_{name}_{item} 0x{value:X}")
        out.append("")
    out += ["#endif", ""]
    return "\n".join(out)


def split_proto(proto):
    i = proto.index("(")
    ret, args = proto[:i].strip(), proto[i + 1:]
    args, attrs = args.rsplit(")", 1)
    return ret, args, attrs


def arg_names(args):
    """the parameter names of a prototype's list, for a call"""
    if args.strip() in ("void", ""):
        return []
    parts, depth, cur = [], 0, ""
    for ch in args:
        if ch == "," and depth == 0:
            parts.append(cur)
            cur = ""
            continue
        depth += ch == "("
        depth -= ch == ")"
        cur += ch
    parts.append(cur)
    names = []
    for p in parts:
        m = re.search(r"\(\*\s*(\w+)\)", p) or re.search(r"(\w+)\s*$", p)
        names.append(m.group(1))
    return names


def kernels():
    return [(n, num, proto) for n, num, proto, *k in D.SYSCALLS if k]


def gen_bios_h():
    out = [HEADER, "#ifndef MX_BIOS_H", "#define MX_BIOS_H", "",
           "/* BIOS (EE kernel) syscalls. Names ending in an i-prefix call are for",
           "   interrupt handlers only.",
           "",
           "   Not for MXOS programs (mx OS plan step 2h-3c): the kernel is their way",
           "   to the BIOS's services (docs/mx-os.md). For maxsdk itself, the kernel",
           "   and standalone ELFs: MX_BIOS_CALLS, which mk/maxsdk.mk defines for",
           "   MX_TARGET=standalone. */",
           "#ifndef MX_BIOS_CALLS",
           '#error "<mx/bios.h>: an MXOS program makes no BIOS calls (MX_TARGET=standalone only, docs/mx-os.md)"',
           "#endif", "",
           "#include <mx/kthreads.h>", "",
           "#ifdef __cplusplus", 'extern "C" {', "#endif", ""]
    for name, num, proto, *_ in D.SYSCALLS:
        ret, args, attrs = split_proto(proto)
        out.append(f"{ret} {name}({args}){attrs};")
    out += ["", "/* The threads, semaphores and interrupt handlers are the kernel's under",
            "   mx-kernel (docs/mx-os-plan.md, step 2d): the calls above go to its table",
            "   when it has set mx__kthreads (src/base/ksys.c), else to the BIOS's own",
            "   syscalls, here. */"]
    for name, num, proto in kernels():
        ret, args, attrs = split_proto(proto)
        out.append(f"{ret} mx__sys_{name[len('mx_bios_'):]}({args}){attrs};")
    out += ["", "/* maxsdk's own (src/base/excset.c): the kernel's syscall entry and exception",
            "   table once it has them (mx OS plan 2h-4), else the BIOS's calls above */",
            "void mx__set_syscall(int number, void *handler);",
            "void *mx__set_handler(int code, void (*handler)(void));"]
    out += ["", "#ifdef __cplusplus", "}", "#endif", "", "#endif", ""]
    return "\n".join(out)


def gen_kthreads_h():
    out = [HEADER, "#ifndef MX_KTHREADS_H", "#define MX_KTHREADS_H", "",
           "/* The kernel's threads, semaphores and interrupt handlers (mx-kernel,",
           "   docs/mx-os-plan.md step 2d): its table, which libmxk calls (src/base/ksys.c),",
           "   with the arguments of the BIOS's calls of the same names. */", "",
           "#ifdef __cplusplus", 'extern "C" {', "#endif", "",
           "struct mx_kthreads {"]
    for name, num, proto in kernels():
        ret, args, attrs = split_proto(proto)
        out.append(f"  {ret} (*{name[len('mx_bios_'):]})({args});")
    out += ["};", "extern const struct mx_kthreads *mx__kthreads;"]
    out += ["", "#ifdef __cplusplus", "}", "#endif", "", "#endif", ""]
    return "\n".join(out)


def gen_syscalls_s():
    out = [HEADER.replace("/*", "#").replace(" */", ""),
           "\t.set noreorder", "\t.text", ""]
    for name, num, _, *k in D.SYSCALLS:
        if k:
            name = "mx__sys_" + name[len("mx_bios_"):]
        out += [f"\t.globl {name}", f"\t.type {name}, @function",
                f"\t.ent {name}", f"{name}:",
                f"\tli $3, {num}", "\tsyscall", "\tjr $31", "\tnop",
                f"\t.end {name}", f"\t.size {name}, .-{name}", ""]
    return "\n".join(out)


def gen_ksys_c():
    out = [HEADER, "/* The BIOS's thread, semaphore and interrupt handler calls, the kernel's",
           "   when it has set its table (mx-kernel, docs/mx-os-plan.md step 2d), else",
           "   the BIOS's syscalls (src/base/syscalls.S). libmxk (MX_KERNEL) has the",
           "   kernel's only (step 2h-3): its start-up stops without a kernel. */", "",
           "#include <mx/bios.h>", "",
           "const struct mx_kthreads *mx__kthreads;", ""]
    for name, num, proto in kernels():
        ret, args, attrs = split_proto(proto)
        short = name[len("mx_bios_"):]
        call = ", ".join(arg_names(args))
        r = "" if ret == "void" else "return "
        out += [f"{ret} {name}({args}) {{",
                "#ifdef MX_KERNEL",
                f"  {r}mx__kthreads->{short}({call});",
                "#else",
                f"  if (mx__kthreads)",
                f"    {r}mx__kthreads->{short}({call});",
                f"  else",
                f"    {r}mx__sys_{short}({call});",
                "#endif",
                "}", ""]
    return "\n".join(out)


def gen_test():
    out = [HEADER, '#include "test.h"', "#include <mx/hw/regs.h>",
           "#include <mx/hw/formats.h>", "#include <mx/bits.h>", "",
           "/* Every field: setting all ones gives exactly its bits, and get(set(x))",
           "   gives x back. */", "void test_gen_fields(void) {"]
    allf = []
    for name, _, _, fields in D.REGS:
        allf += [(f"{name}_{f}", lsb, w) for f, lsb, w in fields]
    for block, _, regs in D.BLOCKS:
        for reg, _, fields in regs:
            allf += [(f"{block}_{reg}_{f}", lsb, w) for f, lsb, w in fields]
    for name, _, fields in D.FORMATS:
        allf += [(f"{name}_{f}", lsb, w) for f, lsb, w in fields]
    for f, lsb, w in allf:
        bits = ((1 << w) - 1) << lsb
        out.append(f"  CHECK_EQ(MX_SET({f}, ~0ull), 0x{bits:X}ull);")
        out.append(f"  CHECK_EQ(MX_GET({f}, MX_SET({f}, 0x{0x5A5A5A5A5A5A5A5A & ((1 << w) - 1):X}ull)), "
                   f"0x{0x5A5A5A5A5A5A5A5A & ((1 << w) - 1):X}ull);")
    out += ["}", ""]
    return "\n".join(out)


def write(rel, text):
    path = os.path.join(ROOT, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    old = open(path).read() if os.path.exists(path) else None
    if old != text:
        with open(path, "w") as f:
            f.write(text)
        print("wrote", rel)


def main():
    write("include/mx/hw/regs.h", gen_regs())
    write("include/mx/hw/formats.h", gen_formats())
    write("include/mx/bios.h", gen_bios_h())
    write("include/mx/kthreads.h", gen_kthreads_h())
    write("src/base/syscalls.S", gen_syscalls_s())
    write("src/base/ksys.c", gen_ksys_c())
    write("../tests/host/test_gen.c", gen_test())


if __name__ == "__main__":
    main()
